"""Regenera tabelas completas no README a partir dos dados de exemplo/catálogo.

Execute na raiz: python scripts/render_readme.py
Evita divergência entre README, ficha JSON e lista de habilidades PES.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '<!-- BEGIN FULL_PES21_FICHA: generated by scripts/render_readme.py -->'
END = '<!-- END FULL_PES21_FICHA -->'


def read_json(rel):
    return json.loads((ROOT / rel).read_text(encoding='utf-8'))


def parse_attributes():
    source = (ROOT/'docs/atributos-pes21.md').read_text(encoding='utf-8')
    rows=[]
    for line in source.splitlines():
        m = re.match(r'^\| `([a-z_]+)` \| ([^|]+) \| ([^|]+) \|$', line)
        if not m:
            continue
        key,label,description=m.groups()
        rows.append((key,label.strip(),description.strip()))
    attributes=rows[:25]
    special=rows[25:29]
    if len(attributes)!=25 or len(special)!=4:
        raise ValueError('O dicionário do PES deve conter 25 atributos e 4 especiais')
    return attributes, special


def build_section():
    garnacho=read_json('examples/garnacho.json')
    lukaku=read_json('examples/lukaku.json')
    catalog=read_json('config/pes21-skills.json')
    attributes,special=parse_attributes()
    skills={x['en']:x for x in catalog['player_skills']}
    if len(skills)!=41 or len(catalog['com_playing_styles'])!=7:
        raise ValueError('Catálogo deve ter 41 habilidades de jogador e 7 estilos COM')
    lines=[BEGIN,
        '## Ficha PES 2021 completa — Garnacho × Lukaku',
        '',
        '**Todos os 25 atributos** (escala do editor de referência: 40–99). As notas abaixo são **propostas de edição**, não medidas extraídas do Sofascore/Opta e **não foram testadas no motor PES**.',
        '',
        '| Grupo | Atributo | O que representa | Garnacho | Lukaku |',
        '| --- | --- | --- | ---: | ---: |']
    for i,(key,label,description) in enumerate(attributes):
        group = 'Ataque/técnica' if i<10 else 'Físico/movimento' if i<17 else 'Defesa' if i<20 else 'Goleiro'
        lines.append(f'| {group} | {label} | {description} | **{garnacho["attributes"][key]}** | **{lukaku["attributes"][key]}** |')
    lines += [
        '',
        '### Parâmetros especiais — todos os 4 campos',
        '',
        '| Parâmetro | Escala | Significado | Garnacho | Lukaku |',
        '| --- | --- | --- | ---: | ---: |'
    ]
    for key,label,description in special:
        rng={'weak_foot_usage':'1–4','weak_foot_accuracy':'1–4','form':'1–8','injury_resistance':'1–3'}[key]
        field_name={'weak_foot_usage':'Pé fraco — uso','weak_foot_accuracy':'Pé fraco — precisão','form':'Forma física','injury_resistance':'Resistência a lesões'}[key]
        lines.append(f'| {field_name} | {rng} | {description} | **{garnacho["other_pes_settings"][key]}** | **{lukaku["other_pes_settings"][key]}** |')
    lines += [
        '',
        '**Resistência (stamina)** = desgaste durante o jogo. **Resistência a lesões** = propensão/susceptibilidade a se lesionar (escala 1–3). **Forma física** = estabilidade da condição ao longo do tempo (1–8). São campos diferentes.',
        '',
        '### Inspirador — 3 categorias (0–2 estrelas)',
        '',
        '| Inspirador | Garnacho | Lukaku |',
        '| --- | ---: | ---: |'
    ]
    inspiration={'carrying':'Carregando / drible','low_pass':'Passe rasteiro','lofted_pass':'Passe alto'}
    for key,label in inspiration.items():
        a=garnacho['other_pes_settings']['inspiration'][key]
        b=lukaku['other_pes_settings']['inspiration'][key]
        lines.append(f'| {label} | {a}/2 | {b}/2 |')
    lines += [
        '',
        '### Habilidades especiais sugeridas para os dois jogadores',
        '',
        'Esta tabela indica **quais habilidades do catálogo foram propostas**; não comprova que o atleta possua a habilidade no PES atual ou no patch da liga.',
        '',
        '| Habilidade (inglês do catálogo) | PT-BR explicativo | Garnacho | Lukaku |',
        '| --- | --- | :---: | :---: |'
    ]
    a=set(garnacho['other_pes_settings']['special_skills_proposed'])
    b=set(lukaku['other_pes_settings']['special_skills_proposed'])
    for en in dict.fromkeys([*garnacho['other_pes_settings']['special_skills_proposed'],*lukaku['other_pes_settings']['special_skills_proposed']]):
        if en not in skills:
            raise ValueError(f'Habilidade proposta não consta no catálogo: {en}')
        lines.append(f'| `{en}` | {skills[en]["pt"]} | {"Proposta" if en in a else "—"} | {"Proposta" if en in b else "—"} |')
    pending=garnacho['other_pes_settings'].get('skills_pending_mapping',[])+lukaku['other_pes_settings'].get('skills_pending_mapping',[])
    lines += [
        '',
        '**Pendência de nomenclatura:** '+('; '.join(pending) if pending else 'nenhuma')+'. Não converter essa descrição automaticamente em habilidade do PES.',
        '',
        '**Estilo de jogo principal:** ainda não definido/validado para os dois exemplos. Não é o mesmo que habilidades especiais ou estilos COM.',
        '',
        '## Catálogo de habilidades disponíveis no PES 2021',
        '',
        '### As 41 habilidades de jogador (lista de referência)',
        '',
        'Os nomes em inglês funcionam como identificadores. As traduções são **explicativas**, podendo variar de acordo com o idioma/patch. Fonte comunitária: [PES Master — PES 2021](https://www.pesmaster.com/pes-2021/search/).',
        '',
        '| Grupo | Habilidade (ID do PES) | PT-BR explicativo | Efeito resumido |',
        '| --- | --- | --- | --- |'
    ]
    for s in catalog['player_skills']:
        lines.append(f'| {s["group"]} | `{s["en"]}` | {s["pt"]} | {s["description"]} |')
    lines += [
        '',
        '### Os 7 estilos de jogo COM — não são habilidades de jogador',
        '',
        '| Estilo COM (inglês) | PT-BR explicativo | Comportamento típico da IA |',
        '| --- | --- | --- |'
    ]
    for s in catalog['com_playing_styles']:
        lines.append(f'| `{s["en"]}` | {s["pt"]} | {s["description"]} |')
    lines += [
        '',
        '**Diferenciação:** os 25 atributos, quatro parâmetros especiais, três inspiradores, 41 habilidades de jogador, sete estilos COM e estilo de jogo principal são categorias distintas. Ver [`docs/habilidades-pes21.md`](docs/habilidades-pes21.md) e [`docs/atributos-pes21.md`](docs/atributos-pes21.md).',
        END
    ]
    return '\n'.join(lines)


def replace_generated(readme):
    if readme.count(BEGIN)!=1 or readme.count(END)!=1:
        raise ValueError('README sem marcadores unívocos de tabela gerada')
    front,rest=readme.split(BEGIN,1)
    _,back=rest.split(END,1)
    return front+build_section()+back


if __name__=='__main__':
    p=ROOT/'README.md'
    p.write_text(replace_generated(p.read_text(encoding='utf-8')),encoding='utf-8')
    print('README: 25 atributos + 4 especiais + 3 inspiradores + habilidades e catálogo atualizado.')
